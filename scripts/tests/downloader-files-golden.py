def transcript_to_dict(value):
    if value is None:
        return None
    return {
        "text": value.text,
        "language": value.language,
        "segments": [
            {
                "id": segment.id,
                "start_ms": segment.start_ms,
                "end_ms": segment.end_ms,
                "text": segment.text,
            }
            for segment in value.segments
        ],
    }


def run_subtitle_case(files):
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        for name, content in files.items():
            # open() 的换行转换会把测试里的 CRLF 再折一次，用字节写才能固定文件内容。
            (root / name).write_bytes(content.encode("utf-8"))
        return transcript_to_dict(subtitles.find_subtitle_transcript(root))


