def posix_name(path):
    return path.as_posix()


def run_video_case(files, stdout, stem, previous):
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        for name, mtime_seconds, size in files:
            target = root / name
            target.write_bytes(b"x" * size)
            os.utime(target, ns=(mtime_seconds * 1_000_000_000, mtime_seconds * 1_000_000_000))
        # `snapshot_video_files` 用 st_mtime_ns；用例里的 mtime_seconds 要换算成纳秒。
        snapshot = {
            posix_name(root / name): (values[0] * 1_000_000_000, values[1])
            for name, values in previous.items()
        }
        resolved_root = root.resolve()

        def selected(path):
            return path.name if path is not None else None

        real_stdout = stdout.replace("<ROOT>", posix_name(root))
        result = {
            "latest": selected(media_preparation.find_latest_video(root)),
            "by_stem": selected(media_preparation.find_video_by_stem(root, stem or None)),
            "from_stdout": selected(
                media_preparation.find_video_from_download_stdout(real_stdout, root)
            ),
            "new_or_updated": selected(media_preparation.find_new_or_updated_video(root, snapshot)),
            "snapshot_entries": len(media_preparation.snapshot_video_files(root)),
        }
        assert resolved_root.exists()
        return result


